function renderRow(check: PulseReport['checks'][number]): string {
  return `        <tr>
          <td>${escapeHtml(check.title)}</td>
          <td class="w">${check.weight}</td>
          <td><span class="tag ${CHECK_CLASSES[check.status]}">${CHECK_LABELS[check.status]}</span></td>
          <td>${escapeHtml(check.message)}</td>
        </tr>`;
}

/** Render a single self-contained HTML file (no external assets or CDN). */
export function renderHtmlReport(
  report: PulseReport,
  options: { generatedAt?: Date; repoUrl?: string | undefined } = {},
): string {
  const generatedAt = options.generatedAt ?? new Date();
  const color = STATUS_COLORS[report.status];
  const repoUrl = options.repoUrl ?? `https://github.com/${report.repo}`;
  const safeRepo = escapeHtml(report.repo);
  const safeUrl = escapeHtml(repoUrl);

  const recommendations =
    report.recommendations.length > 0
      ? `      <ol>\n${report.recommendations
          .map((text) => `        <li>${escapeHtml(text)}</li>`)
          .join('\n')}\n      </ol>`
      : '      <p class="muted">Nothing to fix — this repository is in great shape.</p>';

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>RepoPulse — ${safeRepo} — ${report.score}/100</title>
  <style>${STYLES}</style>
</head>
<body>
  <main>
    <section class="card">
      <header>
        <div>
          <div class="repo"><a href="${safeUrl}" rel="noopener noreferrer">${safeRepo}</a></div>
          <div class="muted">Generated by RepoPulse on ${escapeHtml(generatedAt.toISOString().slice(0, 10))}</div>
        </div>
        <span class="pill" style="background:${color}">${escapeHtml(report.status)}</span>
      </header>
      <div class="score">
        <strong style="color:${color}">${report.score}</strong>
        <span>/ 100</span>
      </div>
      <div class="bar"><div style="width:${report.score}%;background:${color}"></div></div>
    </section>

    <section class="card">
      <h2>Checks</h2>
      <table>
        <thead>
          <tr><th>Check</th><th>Weight</th><th>Status</th><th>Details</th></tr>
        </thead>
        <tbody>
${report.checks.map(renderRow).join('\n')}
        </tbody>
      </table>
    </section>

    <section class="card">
      <h2>Recommendations</h2>
${recommendations}
    </section>

    <footer>Check your repo's pulse. Fix it before it dies.</footer>
  </main>
</body>
</html>
`;
}
